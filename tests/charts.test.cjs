vm.runInContext('let jumpedSeconds=0,stepMark=1000,paused=false,steps=[{title:"Let’s jump!"}],step=0,deadline=21000;'+source.slice(source.indexOf('function accountJumpTime'),source.indexOf('let sessionGoal')),ctx);
