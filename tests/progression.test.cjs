const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const ctx=vm.createContext({});
vm.runInContext(readFileSync('dist/progression.js','utf8'),ctx);
const {nextMilestone,workoutStreak}=ctx;
const session=(date,jumps=0,seconds=0)=>({date,phase:2,jumps,seconds});
assert.equal(nextMilestone([]).target,50);
let sessions=[session('2026-10-01',50)];
assert.equal(nextMilestone(sessions).type,'seconds');
sessions.push(session('2026-10-03',500,49));
assert.equal(nextMilestone(sessions).target,50);
sessions.push(session('2026-10-05',0,50));
assert.equal(nextMilestone(sessions).target,60);
assert.equal(nextMilestone(sessions).type,'jumps');
sessions.push(session('2026-10-07',60));
assert.equal(nextMilestone(sessions).target,60);
assert.equal(nextMilestone(sessions).type,'seconds');
for(let i=0;i<1000;i++){const g=nextMilestone(sessions);sessions.push(session('2026-10-09',g.type==='jumps'?g.target:0,g.type==='seconds'?g.target:0));}
assert.equal(nextMilestone(sessions).unlocked,1003);
const s=dates=>dates.map(d=>session(`2026-10-${d}`));
assert.equal(workoutStreak(s(['01','03','05']),'2026-10-07').count,3);
assert.equal(workoutStreak(s(['01','03','05']),'2026-10-08').count,0);
assert.equal(workoutStreak(s(['01','01','02','03']),'2026-10-03').count,2);
assert.equal(workoutStreak(s(['01','02','04']),'2026-10-04').count,1);
assert.equal(workoutStreak(s(['01','03','06']),'2026-10-06').count,1);
assert.equal(workoutStreak(s(['01','03','04']),'2026-10-06').count,0);
assert.equal(workoutStreak([],'2026-10-06').count,0);
console.log('Progression and every-other-day streak checks passed.');
